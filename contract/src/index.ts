import { CompiledContract } from "@midnight-ntwrk/compact-js";

export * from "./managed/bboard/contract/index.js";
export * from "./witnesses";

import * as CompiledBBoardContract from "./managed/bboard/contract/index.js";
import * as Witnesses from "./witnesses";

export const CompiledBBoardContractContract = CompiledContract.make<
  CompiledBBoardContract.Contract<Witnesses.BBoardPrivateState>
>("BBoard", CompiledBBoardContract.Contract<Witnesses.BBoardPrivateState>).pipe(
  CompiledContract.withWitnesses(Witnesses.witnesses),
  CompiledContract.withCompiledFileAssets("./managed/bboard"),
);

// ============================================================
// Lesson 3.2 Learning Notes - index.ts
// ============================================================
// This is the wiring layer that connects three pieces:
//   1. The compiled contract (managed/bboard/contract/index.js)
//      - Auto-generated by the Compact compiler from bboard.compact
//   2. The TypeScript witness implementation (witnesses.ts)
//      - Supplies the secret key to the contract
//   3. The compiled ZK assets (managed/bboard/)
//      - The zero-knowledge proof circuits
//
// CompiledBBoardContractContract is what the API layer imports
// to deploy and interact with the bulletin board contract.
//
// The .pipe() chain:
//   - Names the contract "BBoard"
//   - Binds the witness implementations
//   - Points to the compiled ZK assets
// ============================================================